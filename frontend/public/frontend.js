// --- FILTERING LOGIC ---
async function applyMultiDeptFilter() {
	const select = document.getElementById("deptSelect");
	// Get all selected options as an array of strings
	const selectedValues = Array.from(select.selectedOptions).map(option => option.value);

	let whereClause = {};

	if (selectedValues.length === 0) {
		// If nothing is selected, show everything
		whereClause = { IS: { dept: "*" } };
	} else if (selectedValues.length === 1) {
		// Simple IS for a single selection
		whereClause = { IS: { dept: selectedValues[0] } };
	} else {
		// Create an array of IS objects for the OR operator
		const orConditions = selectedValues.map(dept => ({
			IS: { dept: dept }
		}));
		whereClause = { OR: orConditions };
	}

	// Reuse your search logic
	const req = await fetch(`/api/v1/search`, {
		method: "POST",
		headers: { "Content-Type": "application/json" },
		body: JSON.stringify({
			kind: "course_offerings",
			query: {
				WHERE: whereClause,
				OPTIONS: {
					COLUMNS: ["dept", "code", "title", "year", "instructor", "avg"],
					ORDER: "dept",
				},
			},
		}),
	});

	const result = await req.json();

	// Clear and redraw table
	const table = document.getElementById("myTable");
	while (table.children.length > 1) {
		table.removeChild(table.lastChild);
	}
	for (const queryResult of result) {
		document.getElementById("myTable").appendChild(createSectionRow2(queryResult));
	}
	closeModal();
}
