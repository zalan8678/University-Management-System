	instructor.textContent = section.instructor;

	const avg = document.createElement("td");
	avg.textContent = section.avg;

	tr.appendChild(dept);
	tr.appendChild(code);
	tr.appendChild(title);
	tr.appendChild(year);
	tr.appendChild(instructor);
